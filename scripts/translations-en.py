def unit(value):
    return {"stringUnit": {"state": "translated", "value": value}}


def plural(one, other):
    return {"variations": {"plural": {"one": unit(one), "other": unit(other)}}}


missing = []
for catalog in sorted(pathlib.Path("App").glob("*/Localizable.xcstrings")):
    data = json.loads(catalog.read_text())
    for key, entry in data["strings"].items():
        if entry.get("shouldTranslate") is False:
            continue
        locs = entry.setdefault("localizations", {})
        if key in PLURAL and PLURAL[key]:
            it1, itn, en1, enn = PLURAL[key]
            locs["it"] = plural(it1, itn)
            locs["en"] = plural(en1, enn)
        elif key in EN:
            locs["en"] = unit(EN[key])
        elif key in SAME:
            locs["en"] = unit(key)
        else:
            missing.append(f"{catalog.parent.name}: {key!r}")
    catalog.write_text(json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True, separators=(",", " : ")) + "\n")

if missing:
    print("Missing English translations:", *missing, sep="\n  ")
    sys.exit(1)
print("All strings translated.")
