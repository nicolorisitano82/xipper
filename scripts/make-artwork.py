def glyph(color, teeth=3, bar=6.6, tooth_w=2.5, tooth_h=2.8, scale=1.0, dx=0.0, dy=0.0):
    """SVG elements of the zipper X in the 40x40 box (optionally scaled and moved)."""
    def p(x, y): return f"{dx + x * scale:.2f} {dy + y * scale:.2f}"
    out = [f'<path d="M{p(7, 7)} L{p(33, 33)} M{p(33, 7)} L{p(7, 33)}" stroke="{color}" '
           f'stroke-width="{bar * scale:.2f}" stroke-linecap="round" fill="none"/>']
    if teeth:
        r = 1 / math.sqrt(2)
        # (arm direction, normal on the top side for upper arms / bottom side for lower arms)
        arms = [((-r, -r), (r, -r)), ((r, -r), (-r, -r)), ((-r, r), (r, r)), ((r, r), (-r, r))]
        spots = [8.6, 12.4, 16.2] if teeth == 3 else [9.6, 14.8]
        path = []
        for (ax, ay), (nx, ny) in arms:
            for t in spots:
                bx, by = 20 + ax * t + nx * (bar / 2 - 0.4), 20 + ay * t + ny * (bar / 2 - 0.4)
                path.append(f"M{p(bx, by)} L{p(bx + nx * (tooth_h + 0.4), by + ny * (tooth_h + 0.4))}")
        out.append(f'<path d="{" ".join(path)}" stroke="{color}" stroke-width="{tooth_w * scale:.2f}" fill="none"/>')
    return "\n  ".join(out)


def svg(body, size=40, defs="", points=None):
    """`points`: the drawn size (template images in the menu bar want 18), default the box size."""
    d = f"<defs>{defs}</defs>\n  " if defs else ""
    shown = points or size
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{shown}" height="{shown}">\n  {d}{body}\n</svg>\n'


def gradient(id, a=BLUE_TOP, b=BLUE_BOTTOM):
    return f'<linearGradient id="{id}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{a}"/><stop offset="1" stop-color="{b}"/></linearGradient>'


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)


def imageset(name, filename, content, template=True):
    folder = os.path.join(ROOT, "App/Xipper/Assets.xcassets", name + ".imageset")
    write(os.path.join(folder, filename), content)
    props = {"preserves-vector-representation": True}
    if template:
        props["template-rendering-intent"] = "template"
    meta = {"images": [{"filename": filename, "idiom": "universal"}], "info": {"author": "xcode", "version": 1},
            "properties": props}
    write(os.path.join(folder, "Contents.json"), json.dumps(meta, indent=2) + "\n")


