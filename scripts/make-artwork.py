#!/usr/bin/env python3
"""Writes Xipper's artwork from one geometry, redrawn from sprite A (docs/design/sprites/sprite-a-app.png,
prompt in docs/design/icon-sprite-prompt.md):

- App/Xipper/AppIcon.icon        app icon for Icon Composer: white zipper X on #4AA3FF -> #0A57D4
                                  (macOS derives the dark, tinted and clear variants from the layers)
- App/Xipper/Assets.xcassets     template symbols: XipperGlyph (menu bar: two teeth per arm, legible at
                                  16 pt), XipperCompress (drop zone of the home window)
- App/XipperFinder/XipperGlyph.svg  Finder toolbar item and menu
- docs/design/artwork/*.svg      every redrawn cell, also the document badges for sprite B
- docs/design/artwork/preview.png contact sheet of the above

The glyph lives in a 40x40 box (the app icon puts it over the central 74% of the canvas): two bars with round caps and three teeth per arm, on the side facing the
top (upper arms) or the bottom (lower arms), as in the sprite.
Document icons (.xiz, and archives when Xipper opens them) are generated by macOS from the app icon
(CFBundleTypeIconSystemGenerated). Usage: python3 scripts/make-artwork.py   (swiftc renders the preview)
"""
import json, math, os, shutil, subprocess, tempfile

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
BLUE_TOP, BLUE_BOTTOM = "#4AA3FF", "#0A57D4"


def glyph(color, teeth=3, bar=6.6, tooth_w=2.5, tooth_h=2.8, scale=1.0, dx=0.0, dy=0.0):
    """SVG elements of the zipper X in the 40x40 box (optionally scaled and moved)."""
    def p(x, y): return f"{dx + x * scale:.2f} {dy + y * scale:.2f}"
    out = [f'<path d="M{p(7, 7)} L{p(33, 33)} M{p(33, 7)} L{p(7, 33)}" stroke="{color}" '
           f'stroke-width="{bar * scale:.2f}" stroke-linecap="round" fill="none"/>']
    if teeth:
        r = 1 / math.sqrt(2)
        # (arm direction, normal on the top side for upper arms / bottom side for lower arms)
        arms = [((-r, -r), (r, -r)), ((r, -r), (-r, -r)), ((-r, r), (r, r)), ((r, r), (-r, r))]
        spots = [8.6, 12.4, 16.2] if teeth == 3 else [9.6, 14.8]
        path = []
        for (ax, ay), (nx, ny) in arms:
            for t in spots:
                bx, by = 20 + ax * t + nx * (bar / 2 - 0.4), 20 + ay * t + ny * (bar / 2 - 0.4)
                path.append(f"M{p(bx, by)} L{p(bx + nx * (tooth_h + 0.4), by + ny * (tooth_h + 0.4))}")
        out.append(f'<path d="{" ".join(path)}" stroke="{color}" stroke-width="{tooth_w * scale:.2f}" fill="none"/>')
    return "\n  ".join(out)


def svg(body, size=40, defs="", points=None):
    """`points`: the drawn size (template images in the menu bar want 18), default the box size."""
    d = f"<defs>{defs}</defs>\n  " if defs else ""
    shown = points or size
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{shown}" height="{shown}">\n  {d}{body}\n</svg>\n'


def gradient(id, a=BLUE_TOP, b=BLUE_BOTTOM):
    return f'<linearGradient id="{id}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{a}"/><stop offset="1" stop-color="{b}"/></linearGradient>'


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)


def imageset(name, filename, content, template=True):
    folder = os.path.join(ROOT, "App/Xipper/Assets.xcassets", name + ".imageset")
    write(os.path.join(folder, filename), content)
    props = {"preserves-vector-representation": True}
    if template:
        props["template-rendering-intent"] = "template"
    meta = {"images": [{"filename": filename, "idiom": "universal"}], "info": {"author": "xcode", "version": 1},
            "properties": props}
    write(os.path.join(folder, "Contents.json"), json.dumps(meta, indent=2) + "\n")


# --- the artwork, cell by cell (row, column of sprite A) -------------------------------------------

art = {}
squircle = '<rect x="2" y="2" width="36" height="36" rx="9" fill="{}"/>'
art["r1c1-app-icon"] = svg(squircle.format("url(#g)") + "\n  " + glyph("#FFFFFF", scale=0.74, dx=5.2, dy=5.2), defs=gradient("g"))
art["r1c2-app-icon-dark"] = svg(squircle.format("#1C1C1E") + "\n  " + glyph("url(#g)", scale=0.74, dx=5.2, dy=5.2),
                                defs=gradient("g", "#5AC8FA", "#2F7BF5"))
art["r1c3-app-icon-tinted"] = svg(squircle.format("#E5E5EA") + "\n  " + glyph("#8E8E93", scale=0.74, dx=5.2, dy=5.2))
art["r1c4-app-icon-small"] = svg(squircle.format("url(#g)") + "\n  " + glyph("#FFFFFF", teeth=0, bar=7.0, scale=0.74, dx=5.2, dy=5.2),
                                 defs=gradient("g"))
menu_glyph = glyph("#000000", teeth=2, bar=6.6, tooth_w=2.8, tooth_h=3.2)
art["r2c1-menu-bar"] = svg(menu_glyph)
arrows = []
for sx, sy in [(-1, -1), (1, -1), (-1, 1), (1, 1)]:  # four arrows from the corners toward the centre
    tip = (20 + sx * 10.5, 20 + sy * 10.5)
    tail = (20 + sx * 18, 20 + sy * 18)
    arrows.append(f"M{tail[0]} {tail[1]} L{tip[0]} {tip[1]} M{tip[0]} {tip[1] + sy * 4.2} L{tip[0]} {tip[1]} L{tip[0] + sx * 4.2} {tip[1]}")
art["r2c2-compress"] = svg(glyph("#000000", teeth=2, bar=6.4, tooth_w=2.8, tooth_h=3.0, scale=0.56, dx=8.8, dy=8.8) +
                           f'\n  <path d="{" ".join(arrows)}" stroke="#000000" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round" fill="none"/>')
art["r2c3-extract"] = svg('<path d="M6 21 L6 32 Q6 34 8 34 L32 34 Q34 34 34 32 L34 21 M6 21 L13 21 L15.5 25 L24.5 25 L27 21 L34 21" '
                          'stroke="#000000" stroke-width="2.8" stroke-linejoin="round" stroke-linecap="round" fill="none"/>\n  '
                          '<path d="M20 20 Q21 10 31 8 M26 5.5 L31.5 8 L28.5 13" stroke="#000000" stroke-width="2.8" stroke-linecap="round" stroke-linejoin="round" fill="none"/>')
art["r2c4-verify"] = svg('<path d="M20 4 L33 8.5 L33 18 Q33 29 20 36 Q7 29 7 18 L7 8.5 Z" stroke="#000000" stroke-width="2.8" stroke-linejoin="round" fill="none"/>\n  '
                         '<path d="M13.5 20 L18 24.5 L27 15.5" stroke="#000000" stroke-width="3" stroke-linecap="round" stroke-linejoin="round" fill="none"/>\n  '
                         '<path d="M22 20.5 L24 22.5 M24.6 18 L26.6 20" stroke="#000000" stroke-width="1.4" fill="none"/>')
art["r3c1-badge-encrypted"] = svg('<path d="M13 18 L13 12.5 Q13 6 20 6 Q27 6 27 12.5 L27 18" stroke="url(#g)" stroke-width="4" fill="none"/>\n  '
                                  '<rect x="7" y="17" width="26" height="19" rx="5" fill="url(#g)"/>\n  ' +
                                  glyph("#FFFFFF", teeth=2, bar=5.5, tooth_w=1.8, tooth_h=2.2, scale=0.34, dx=13.2, dy=19.7), defs=gradient("g"))
art["r3c2-badge-damaged"] = svg('<path d="M20 5 L36 33 L4 33 Z" fill="url(#o)" stroke="url(#o)" stroke-width="3" stroke-linejoin="round"/>\n  '
                                '<path d="M20 12 L20 24" stroke="#FFFFFF" stroke-width="3.4" stroke-linecap="round"/>\n  '
                                '<path d="M17.6 14.5 L22.4 14.5 M17.6 18 L22.4 18 M17.6 21.5 L22.4 21.5" stroke="#FFFFFF" stroke-width="1.2"/>\n  '
                                '<circle cx="20" cy="28.6" r="2.1" fill="#FFFFFF"/>', defs=gradient("o", "#FFC300", "#FF7A00"))
art["r3c3-badge-beta"] = svg('<path d="M5 13 Q5 9 9 9 L27 9 L36 20 L27 31 L9 31 Q5 31 5 27 Z" fill="url(#p)" stroke="url(#p)" stroke-width="2" stroke-linejoin="round"/>\n  '
                             '<circle cx="28.5" cy="20" r="2.2" fill="#FFFFFF"/>\n  '
                             '<path d="M15 12.5 Q16 19 22.5 20 Q16 21 15 27.5 Q14 21 7.5 20 Q14 19 15 12.5 Z" fill="#F4F0FF"/>',
                             defs=gradient("p", "#A97BFF", "#6C47E0"))
def helix(sign):  # one strand of the double helix, as a polyline through a sine
    pts = [(20 + sign * 9 * math.sin(2 * math.pi * (y - 4) / 32), y) for y in [4 + n * 0.5 for n in range(65)]]
    return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts)
rungs = []
for y in (8.5, 12, 24, 27.5, 31):  # where the strands are apart: a rung with zipper notches
    half = abs(9 * math.sin(2 * math.pi * (y - 4) / 32)) - 2.2
    if half > 2:
        rungs.append(f"M{20 - half:.2f} {y} L{20 + half:.2f} {y}")
art["r3c4-badge-genomics"] = svg(f'<path d="{" ".join(rungs)}" stroke="#30B0C7" stroke-width="1.8" stroke-dasharray="1.3 1.1" fill="none"/>\n  '
                                 f'<path d="{helix(1)}" stroke="url(#t)" stroke-width="3.4" stroke-linecap="round" stroke-linejoin="round" fill="none"/>\n  '
                                 f'<path d="{helix(-1)}" stroke="url(#t)" stroke-width="3.4" stroke-linecap="round" stroke-linejoin="round" fill="none"/>',
                                 defs=gradient("t", "#5AD8E6", "#1E9EB5"))
art["r4c1-drop-zone"] = svg('<rect x="3" y="7" width="34" height="26" rx="6" stroke="#2F86F6" stroke-width="1.6" stroke-dasharray="3.2 2.2" fill="none"/>\n  ' +
                            glyph("url(#g)", scale=0.42, dx=11.6, dy=11.6) +
                            '\n  <path d="M6 20 L11 20 M9 18 L11 20 L9 22 M34 20 L29 20 M31 18 L29 20 L31 22" stroke="#2FA8F6" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" fill="none"/>',
                            defs=gradient("g"))
art["r4c3-all-good"] = svg('<circle cx="20" cy="20" r="17" fill="url(#g)"/>\n  '
                           '<path d="M11.5 20.5 L17.5 26.5 L29 14.5" stroke="#FFFFFF" stroke-width="4.2" stroke-linecap="round" stroke-linejoin="round" fill="none"/>\n  '
                           '<path d="M22.6 21.4 L24.4 23.2 M25.4 18.4 L27.2 20.2" stroke="#FFFFFF" stroke-width="1.6" fill="none"/>', defs=gradient("g"))
art["r4c4-progress"] = svg('<circle cx="20" cy="20" r="16" stroke="#D1D1D6" stroke-width="3.6" fill="none"/>\n  '
                           '<path d="M20 4 A16 16 0 1 1 4.8 25" stroke="url(#g)" stroke-width="3.6" stroke-linecap="round" fill="none"/>\n  ' +
                           glyph("url(#g)", teeth=2, bar=6.4, tooth_w=2.2, tooth_h=2.6, scale=0.42, dx=11.6, dy=11.6), defs=gradient("g"))

out_dir = os.path.join(ROOT, "docs/design/artwork")
if os.path.isdir(out_dir):
    shutil.rmtree(out_dir)
for name, content in art.items():
    write(os.path.join(out_dir, name + ".svg"), content)

# --- app icon (Icon Composer bundle): the glyph box over the central 74% of 1024 ----------------

icon_root = os.path.join(ROOT, "App/Xipper/AppIcon.icon")
k, o = 1024 * 0.74 / 40, 1024 * 0.13
write(os.path.join(icon_root, "Assets/glyph.svg"),
      svg(glyph("#FFFFFF", scale=k, dx=o, dy=o), size=1024))
icon = {
    "fill": {"linear-gradient": ["extended-srgb:0.29020,0.63922,1.00000,1.00000",
                                 "extended-srgb:0.03922,0.34118,0.83137,1.00000"]},
    "groups": [{"layers": [{"image-name": "glyph.svg", "name": "glyph"}]}],
    "supported-platforms": {"squares": ["macOS"]},
}
write(os.path.join(icon_root, "icon.json"), json.dumps(icon, indent=2) + "\n")

# --- template symbols in the app's asset catalog, and the Finder extension's glyph -------------------

imageset("XipperGlyph", "XipperGlyph.svg", svg(menu_glyph, points=18))  # menu bar: 18 pt like system symbols
imageset("XipperCompress", "XipperCompress.svg", art["r2c2-compress"])
write(os.path.join(ROOT, "App/XipperFinder/XipperGlyph.svg"), art["r2c1-menu-bar"])

# --- raster: a preview sheet of the artwork -----------------------------------------

RASTER = r'''
import AppKit
let a = CommandLine.arguments
if a[1] == "png" {   // png <svg> <out.png> <pixels>
    let img = NSImage(contentsOfFile: a[2])!, px = Int(a[4])!
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: px, pixelsHigh: px, bitsPerSample: 8, samplesPerPixel: 4,
                               hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    img.draw(in: NSRect(x: 0, y: 0, width: px, height: px))
    NSGraphicsContext.restoreGraphicsState()
    try! rep.representation(using: .png, properties: [:])!.write(to: URL(fileURLWithPath: a[3]))
} else {             // sheet <out.png> <svg>...  (6 per row, 128 px, light background)
    let files = Array(a.dropFirst(3)), cell = 128, cols = 6, rows = (files.count + cols - 1) / cols
    let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: cols * cell, pixelsHigh: rows * cell, bitsPerSample: 8,
                               samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    NSColor(white: 0.95, alpha: 1).setFill()
    NSRect(x: 0, y: 0, width: cols * cell, height: rows * cell).fill()
    for (i, f) in files.enumerated() {
        NSImage(contentsOfFile: f)!.draw(in: NSRect(x: (i % cols) * cell + 14, y: (rows - 1 - i / cols) * cell + 14, width: cell - 28, height: cell - 28))
    }
    NSGraphicsContext.restoreGraphicsState()
    try! rep.representation(using: .png, properties: [:])!.write(to: URL(fileURLWithPath: a[2]))
}
'''
tmp = tempfile.mkdtemp()
try:
    src = os.path.join(tmp, "raster.swift")
    open(src, "w").write(RASTER)
    tool = os.path.join(tmp, "raster")
    subprocess.run(["swiftc", "-O", src, "-o", tool], check=True)
    sheet = [os.path.join(out_dir, n + ".svg") for n in art]
    subprocess.run([tool, "sheet", os.path.join(out_dir, "preview.png")] + sheet, check=True)
finally:
    shutil.rmtree(tmp)
print("artwork written:", len(art), "cells, app icon, 2 symbols")
