#!/usr/bin/env python3
"""Writes Vendor/MANIFEST.json: for every vendored library its version, upstream and the SHA-256
of each file, so a change to the sources that did not come from an update shows up
(VendorManifestTests compares the files with it). Run after updating a library:
    python3 -I scripts/make-vendor-manifest.py
Files marked "ours" are Xipper's glue (umbrella headers, module maps, shims, generated configs)."""
import hashlib, json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Vendor")

LIBRARIES = {
    "zstd": ("1.5.7", "https://github.com/facebook/zstd", "v1.5.7"),
    "libdeflate": ("1.24", "https://github.com/ebiggers/libdeflate", "v1.24"),
    "xz": ("5.8.4", "https://github.com/tukaani-project/xz", "v5.8.4 (d3e650e)"),
    "lzma-sdk": ("26.05", "https://github.com/ip7z/7zip", "26.05"),
    "htscodecs": ("1.6.7", "https://github.com/samtools/htscodecs", "b9fc194"),
    "libarchive": ("3.8.11", "https://github.com/libarchive/libarchive", "v3.8.11 (03036ff)"),
    "lz4": ("1.10.0", "https://github.com/lz4/lz4", "v1.10.0"),
    "brotli": ("1.2.1", "https://github.com/google/brotli", "v1.2.1"),
    "argon2": ("20190702", "https://github.com/P-H-C/phc-winner-argon2", "62358ba"),
}

# Xipper's own files inside Vendor/ (README "Local modifications").
OURS = {
    "zstd/include/CZstd.h", "libdeflate/include/CDeflate.h", "xz/src/liblzma/api/module.modulemap",
    "htscodecs/include/CHtsCodecs.h", "htscodecs/htscodecs/config.h", "htscodecs/htscodecs/version.h",
    "libarchive/include/CArchive.h", "libarchive/libarchive/config.h", "lz4/include/CLZ4.h",
    "brotli/c/include/module.modulemap", "lzma-sdk/include/CLzmaSDK.h", "lzma-sdk/shim/xs_ppmd.c",
    "lzma-sdk/shim/xs_lzdec.c",
}


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main():
    out = {"comment": "Generated by scripts/make-vendor-manifest.py; checked by VendorManifestTests.", "libraries": []}
    seen = set()
    for name, (version, upstream, ref) in LIBRARIES.items():
        base = os.path.join(ROOT, name)
        files = {}
        for d, dirs, names in os.walk(base):
            dirs.sort()
            for n in sorted(names):
                if n == ".DS_Store":
                    continue
                rel = os.path.relpath(os.path.join(d, n), ROOT)
                files[rel] = {"sha256": sha256(os.path.join(d, n))} | ({"ours": True} if rel in OURS else {})
        seen.add(name)
        out["libraries"].append({"name": name, "version": version, "upstream": upstream, "ref": ref, "files": files})
    extra = [e for e in os.listdir(ROOT) if os.path.isdir(os.path.join(ROOT, e)) and e not in seen]
    if extra:
        sys.exit(f"Vendor folders missing from LIBRARIES: {extra}")
    with open(os.path.join(ROOT, "MANIFEST.json"), "w") as f:
        json.dump(out, f, indent=1, sort_keys=False)
        f.write("\n")
    print(f"{sum(len(l['files']) for l in out['libraries'])} files in {len(out['libraries'])} libraries")


main()
